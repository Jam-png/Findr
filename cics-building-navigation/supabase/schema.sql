-- Findr database schema for Supabase (PostgreSQL).
-- Run the entire file once in Supabase Dashboard > SQL Editor > New query.
-- Supabase's service-role key is used only by the Express backend; do not put it in frontend code.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  full_name varchar(120) not null,
  username varchar(50) not null unique,
  email varchar(120) not null unique,
  password_hash varchar(255) not null,
  role text not null default 'student' check (role in ('student', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.buildings (
  id bigint generated by default as identity primary key,
  building_name varchar(120) not null unique,
  description text,
  location varchar(255),
  created_at timestamptz not null default now()
);

create table if not exists public.floors (
  id bigint generated by default as identity primary key,
  building_id bigint not null references public.buildings(id) on delete cascade,
  floor_number integer not null,
  floor_name varchar(80),
  unique (building_id, floor_number)
);

create table if not exists public.rooms (
  id bigint generated by default as identity primary key,
  floor_id bigint not null references public.floors(id) on delete cascade,
  room_name varchar(120) not null,
  room_number varchar(30) not null,
  room_type varchar(60) not null default 'Classroom',
  description text,
  unique (floor_id, room_number)
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete restrict,
  building_id bigint references public.buildings(id) on delete set null,
  room_id bigint references public.rooms(id) on delete set null,
  category varchar(80) not null,
  priority text not null default 'Medium' check (priority in ('Low', 'Medium', 'High', 'Urgent')),
  title varchar(160) not null,
  description text not null,
  image_path text,
  contact_name varchar(120),
  contact_email varchar(120),
  status text not null default 'Submitted' check (status in ('Submitted', 'Under Review', 'In Progress', 'Resolved', 'Rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists floors_building_id_idx on public.floors(building_id);
create index if not exists rooms_floor_id_idx on public.rooms(floor_id);
create index if not exists reports_user_id_created_at_idx on public.reports(user_id, created_at desc);
create index if not exists reports_created_at_idx on public.reports(created_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists reports_set_updated_at on public.reports;
create trigger reports_set_updated_at
before update on public.reports
for each row execute function public.set_updated_at();

-- The backend uses the Supabase service-role key. Enable RLS so anon/authenticated
-- browser clients cannot read these tables directly. The service role bypasses RLS.
alter table public.users enable row level security;
alter table public.buildings enable row level security;
alter table public.floors enable row level security;
alter table public.rooms enable row level security;
alter table public.reports enable row level security;

-- Grant the backend service role access. No direct anon/authenticated table grants are added.
grant usage on schema public to service_role;
grant all privileges on all tables in schema public to service_role;
grant all privileges on all sequences in schema public to service_role;

