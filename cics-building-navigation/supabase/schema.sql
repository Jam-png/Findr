select b.id, x.floor_number, x.floor_name
from public.buildings b
cross join (values
  (1, '1st Floor'),
  (2, '2nd Floor'),
  (3, '3rd Floor'),
  (4, '4th Floor'),
  (5, '5th Floor')
) as x(floor_number, floor_name)
