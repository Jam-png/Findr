-- Run once in Supabase Dashboard > SQL Editor > New query.
-- Required by Findr's email verification / password reset feature.
create table if not exists public.password_reset_codes (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  code_hash char(64) not null,
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists password_reset_codes_user_created_idx
  on public.password_reset_codes(user_id, created_at desc);

alter table public.password_reset_codes enable row level security;
grant all privileges on public.password_reset_codes to service_role;
grant usage, select on sequence public.password_reset_codes_id_seq to service_role;
